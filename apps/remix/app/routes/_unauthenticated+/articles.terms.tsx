import { getLegalEntity, LEGAL_PRIVACY_PATH } from '@documenso/lib/constants/legal-entity';
import { SIGNING_CONSENT_VERSION } from '@documenso/lib/constants/signing-consent';
import { msg } from '@lingui/core/macro';
import { Link } from 'react-router';

import { appMetaTags } from '~/utils/meta';

import type { Route } from './+types/articles.terms';

export function meta() {
  return appMetaTags(msg`Terms of Use`);
}

export const loader = () => {
  const legalEntity = getLegalEntity();

  // Only published once the operating entity has been configured.
  if (!legalEntity) {
    throw new Response('Not Found', { status: 404 });
  }

  return { legalEntity };
};

